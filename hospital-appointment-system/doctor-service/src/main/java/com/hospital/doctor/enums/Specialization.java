package com.hospital.doctor.enums;

/**
 * ============================================================================
 * Specialization Enum
 * ============================================================================
 * Defines all valid medical specializations that a doctor can have
 * in the Hospital Appointment System. This enum is used to validate
 * and categorize doctors by their area of medical expertise.
 *
 * Supported specializations:
 * - CARDIOLOGY:        Heart and cardiovascular system
 * - NEUROLOGY:         Brain and nervous system
 * - ORTHOPEDICS:       Musculoskeletal system (bones, joints, muscles)
 * - DERMATOLOGY:       Skin, hair, and nails
 * - PEDIATRICS:        Children's health and development
 * - GENERAL_MEDICINE:  Primary care and general health
 * - ENT:               Ear, Nose, and Throat
 * - OPHTHALMOLOGY:     Eyes and vision
 * ============================================================================
 */
public enum Specialization {

    CARDIOLOGY,
    NEUROLOGY,
    ORTHOPEDICS,
    DERMATOLOGY,
    PEDIATRICS,
    GENERAL_MEDICINE,
    ENT,
    OPHTHALMOLOGY
}
